-- 3. TABLA: USUARIOS (base de autenticación)
CREATE TABLE IF NOT EXISTS USUARIOS (
    ID_USUARIO SERIAL PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    PRIMER_APELLIDO VARCHAR(50),
    SEGUNDO_APELLIDO VARCHAR(50),
    EMAIL VARCHAR(150) NOT NULL,
    CONTRASENA VARCHAR(255) NOT NULL,
    ROL VARCHAR(20) DEFAULT 'AUTOR' NOT NULL,
    ESTADO_USUARIO VARCHAR(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT USUARIOS_APELLIDOS_CK CHECK (PRIMER_APELLIDO IS NOT NULL OR SEGUNDO_APELLIDO IS NOT NULL),
    CONSTRAINT USUARIOS_EMAIL_UQ UNIQUE (EMAIL),
    CONSTRAINT USUARIOS_EMAIL_CK CHECK (EMAIL ~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
    CONSTRAINT USUARIOS_ROL_CK CHECK (ROL IN ('ADMIN', 'AUTOR')),
    CONSTRAINT USUARIOS_ESTADO_USUARIO_CK CHECK (ESTADO_USUARIO IN ('ACTIVO', 'INACTIVO'))
);

