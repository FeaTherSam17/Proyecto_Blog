-- 4. TABLA: AUTORES (datos adicionales del autor — FK a USUARIOS)
CREATE TABLE IF NOT EXISTS AUTORES (
    ID_AUTOR INTEGER PRIMARY KEY,
    COD_SEXO CHAR(1) NOT NULL,
    TELEFONO VARCHAR(10) NOT NULL,
    BIOGRAFIA VARCHAR(500) NOT NULL,
    FECHA_REGISTRO DATE DEFAULT CURRENT_DATE NOT NULL,
    ESTADO_AUTOR VARCHAR(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT AUTORES_SEXO_FK FOREIGN KEY (COD_SEXO) REFERENCES CAT_SEXOS(COD_SEXO),
    CONSTRAINT AUTORES_ID_AUTOR_FK FOREIGN KEY (ID_AUTOR) REFERENCES USUARIOS(ID_USUARIO),
    CONSTRAINT AUTORES_TELEFONO_CK CHECK (TELEFONO ~ '^[0-9]{10}$'),
    CONSTRAINT AUTORES_ESTADO_CK CHECK (ESTADO_AUTOR IN ('ACTIVO', 'INACTIVO'))
);

-- 5. TABLA: PUBLICACIONES
CREATE TABLE IF NOT EXISTS PUBLICACIONES (
    ID_PUBLICACION SERIAL PRIMARY KEY,
    TITULO VARCHAR(200) NOT NULL,
    ID_AUTOR INTEGER NOT NULL,
    ID_CATEGORIA INTEGER NOT NULL,
    FECHA_PUBLICACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    TEXTO_PUBLICACION TEXT NOT NULL,
    ESTADO_PUBLICACION VARCHAR(30) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PUB_ID_AUTOR_FK FOREIGN KEY (ID_AUTOR) REFERENCES AUTORES (ID_AUTOR),
    CONSTRAINT PUB_ID_CATEGORIA_FK FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIAS (ID_CATEGORIA),
    CONSTRAINT PUB_ESTADO_CK CHECK (ESTADO_PUBLICACION IN ('ACTIVO', 'INACTIVO', 'PENDIENTE_VERIFICACION', 'SUSPENDIDO', 'ELIMINADO'))
);
