-- 8. BITÁCORA DE COMPORTAMIENTO DEL INICIO DE SESIÓN
-- Esta tabla no almacena contraseñas ni respuestas del CAPTCHA. Registra únicamente
-- el resultado del acceso y los datos necesarios para medir seguridad y uso:
-- intentos exitosos/fallidos, motivo, duración, hora, IP y navegador.
-- COMPORTAMIENTO contiene los contadores y tiempos enviados por Vue.
-- CLASIFICACION_COMPORTAMIENTO conserva la señal orientativa del backend.
CREATE TABLE METRICAS_ACCESO (
    ID_EVENTO BIGSERIAL PRIMARY KEY,
    ID_USUARIO INTEGER,
    EMAIL_INGRESADO VARCHAR(150),
    TIPO_EVENTO VARCHAR(20) NOT NULL,
    MOTIVO VARCHAR(40) NOT NULL,
    DIRECCION_IP INET,
    AGENTE_USUARIO VARCHAR(500),
    DURACION_MS INTEGER,
    -- Resumen de interacción: movimientos, keyup, intervalos y tiempo focus-submit.
    COMPORTAMIENTO JSONB,
    CLASIFICACION_COMPORTAMIENTO VARCHAR(20),
    FECHA_EVENTO TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT METRICAS_ACCESO_USUARIO_FK
        FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO) ON DELETE SET NULL,
    CONSTRAINT METRICAS_ACCESO_TIPO_CK
        CHECK (TIPO_EVENTO IN ('LOGIN', 'LOGOUT')),
    CONSTRAINT METRICAS_ACCESO_MOTIVO_CK
        CHECK (MOTIVO IN (
            'EXITOSO',
            'CREDENCIALES_INVALIDAS',
            'CAMPOS_REQUERIDOS',
            'CAPTCHA_INVALIDO',
            'USUARIO_INACTIVO',
            'BLOQUEADO_RATE_LIMIT',
            'ERROR_INTERNO'
        )),
    CONSTRAINT METRICAS_ACCESO_DURACION_CK
        CHECK (DURACION_MS IS NULL OR DURACION_MS >= 0),
    CONSTRAINT METRICAS_ACCESO_CLASIFICACION_CK
        CHECK (
            CLASIFICACION_COMPORTAMIENTO IS NULL
            OR CLASIFICACION_COMPORTAMIENTO IN ('HUMANO', 'SOSPECHOSO', 'INDETERMINADO')
        )
);

-- Índices para consultar tendencias por fecha, resultado y usuario sin recorrer
-- toda la bitácora. La retención puede definirse posteriormente según la política
-- de privacidad del proyecto.
CREATE INDEX METRICAS_ACCESO_FECHA_IDX
    ON METRICAS_ACCESO (FECHA_EVENTO);
CREATE INDEX METRICAS_ACCESO_RESULTADO_IDX
    ON METRICAS_ACCESO (TIPO_EVENTO, MOTIVO, FECHA_EVENTO);
CREATE INDEX METRICAS_ACCESO_USUARIO_IDX
    ON METRICAS_ACCESO (ID_USUARIO, FECHA_EVENTO);

-- Vista de indicadores diarios para el panel administrativo o reportes.
-- Resume volumen, éxito, fallos, usuarios distintos y duración promedio.
CREATE VIEW VW_METRICAS_LOGIN_DIARIAS AS
SELECT
    DATE(FECHA_EVENTO) AS FECHA,
    COUNT(*) FILTER (WHERE TIPO_EVENTO = 'LOGIN') AS INTENTOS_LOGIN,
    COUNT(*) FILTER (WHERE TIPO_EVENTO = 'LOGIN' AND MOTIVO = 'EXITOSO') AS LOGIN_EXITOSOS,
    COUNT(*) FILTER (WHERE TIPO_EVENTO = 'LOGIN' AND MOTIVO <> 'EXITOSO') AS LOGIN_FALLIDOS,
    COUNT(DISTINCT ID_USUARIO) FILTER (
        WHERE TIPO_EVENTO = 'LOGIN' AND MOTIVO = 'EXITOSO'
    ) AS USUARIOS_UNICOS,
    ROUND(
        100.0 * COUNT(*) FILTER (
            WHERE TIPO_EVENTO = 'LOGIN' AND MOTIVO = 'EXITOSO'
        ) / NULLIF(COUNT(*) FILTER (WHERE TIPO_EVENTO = 'LOGIN'), 0),
        2
    ) AS TASA_EXITO_PORCENTAJE,
    ROUND(AVG(DURACION_MS) FILTER (
        WHERE TIPO_EVENTO = 'LOGIN' AND MOTIVO = 'EXITOSO'
    ), 2) AS DURACION_PROMEDIO_MS
FROM METRICAS_ACCESO
GROUP BY DATE(FECHA_EVENTO)
ORDER BY FECHA DESC;

